export type StudioType = 'pdf' | 'image' | 'extra';

export type ExecutionBadge =
  | 'Client-Side (Browser)'
  | 'Hybrid (Client + Server)'
  | 'Hybrid (Client + Gemini AI)'
  | 'Client-Side (Web Worker + OffscreenCanvas)'
  | 'Client-Side (Web Worker / WebGL)'
  | 'Client-Side (WebGL / LUT Worker)'
  | 'Client-Side (Web Worker + Canvas)'
  | 'Client-Side (Web Crypto)';

export interface ToolParamOption {
  label: string;
  value: string;
}

export interface ToolParamDefinition {
  key: string;
  label: string;
  type: 'select' | 'number' | 'text' | 'textarea' | 'range' | 'boolean' | 'color';
  defaultValue: any;
  min?: number;
  max?: number;
  step?: number;
  options?: ToolParamOption[];
  placeholder?: string;
  unit?: string;
}

export interface StudioTool {
  id: string;
  number: number;
  studio: StudioType;
  categoryId: string;
  categoryName: string;
  name: string;
  shortDesc: string;
  executionMode: ExecutionBadge;
  engineLabel: string;
  outputExt: string;
  supportsBatch?: boolean;
  usesWorker?: boolean;
  params: ToolParamDefinition[];
}

export interface ToolCategory {
  id: string;
  studio: StudioType;
  index: number;
  name: string;
  description: string;
}

