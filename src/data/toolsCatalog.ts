export function searchStudioTools(query: string, studio?: StudioType): StudioTool[] {
  const pool =
    studio === 'pdf'
      ? PDF_TOOLS
      : studio === 'image'
      ? IMAGE_TOOLS
      : studio === 'extra'
      ? EXTRA_TOOLS
      : [...PDF_TOOLS, ...IMAGE_TOOLS, ...EXTRA_TOOLS];
  const q = query.trim().toLowerCase();
  if (!q) return pool;

  const cleanNum = q.replace(/^#0*/, '');
  return pool.filter((t) => {
    const paddedNum = String(t.number).padStart(2, '0');
    const studioLabel =
      t.studio === 'extra' ? 'calculator converter calc extra' : t.studio;
    const studioNumTag = `${t.studio} ${t.number}`;
    const studioHashTag = `${t.studio} #${t.number}`;
    const studioPaddedTag = `${t.studio} #${paddedNum}`;
    const calcNumTag = t.studio === 'extra' ? `calc ${t.number} converter ${t.number} calc & converter #${paddedNum}` : '';
    return (
      t.name.toLowerCase().includes(q) ||
      t.shortDesc.toLowerCase().includes(q) ||
      t.categoryName.toLowerCase().includes(q) ||
      t.engineLabel.toLowerCase().includes(q) ||
      studioLabel.includes(q) ||
      String(t.number) === cleanNum ||
      paddedNum === q.replace(/^#/, '') ||
      studioNumTag.includes(q) ||
      studioHashTag.includes(q) ||
      studioPaddedTag.includes(q) ||
      (calcNumTag ? calcNumTag.includes(q) : false)
    );
  });
}
